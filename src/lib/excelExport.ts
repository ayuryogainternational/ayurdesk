import ExcelJS from 'exceljs';
import { DailyReport } from '../types';
import { getReportGenerationTimestamp } from './timezone';

export interface ExcelExportOptions {
  records: DailyReport[];
  scopeTitle: string;
  periodText: string;
  adminName: string;
  fileName?: string;
}

export async function exportToExcel({
  records,
  scopeTitle,
  periodText,
  adminName,
  fileName,
}: ExcelExportOptions): Promise<void> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'AyurDesk - Ayuryoga International';
  workbook.created = new Date();

  const worksheet = workbook.addWorksheet('Operations Report', {
    pageSetup: { orientation: 'landscape', paperSize: 9 }, // A4 landscape
    views: [{ showGridLines: true }],
  });

  // 1. Title Banner
  worksheet.mergeCells('A1:H1');
  const titleCell = worksheet.getCell('A1');
  titleCell.value = 'AYURYOGA INTERNATIONAL';
  titleCell.font = { name: 'Arial', size: 16, bold: true, color: { argb: 'FF103B37' } };
  titleCell.alignment = { vertical: 'middle', horizontal: 'left' };
  worksheet.getRow(1).height = 28;

  // 2. Subtitle
  worksheet.mergeCells('A2:H2');
  const subtitleCell = worksheet.getCell('A2');
  subtitleCell.value = `AyurDesk Operations Report - ${scopeTitle}`;
  subtitleCell.font = { name: 'Arial', size: 12, bold: true, color: { argb: 'FF23675B' } };
  subtitleCell.alignment = { vertical: 'middle', horizontal: 'left' };
  worksheet.getRow(2).height = 22;

  // 3. Metadata Rows
  worksheet.getCell('A3').value = 'Report Period:';
  worksheet.getCell('A3').font = { bold: true, size: 10, color: { argb: 'FF555555' } };
  worksheet.getCell('B3').value = periodText;
  worksheet.getCell('B3').font = { size: 10 };

  worksheet.getCell('D3').value = 'Generated At:';
  worksheet.getCell('D3').font = { bold: true, size: 10, color: { argb: 'FF555555' } };
  worksheet.getCell('E3').value = getReportGenerationTimestamp();
  worksheet.getCell('E3').font = { size: 10 };

  worksheet.getCell('A4').value = 'Generated By:';
  worksheet.getCell('A4').font = { bold: true, size: 10, color: { argb: 'FF555555' } };
  worksheet.getCell('B4').value = `${adminName} (Administrator)`;
  worksheet.getCell('B4').font = { size: 10 };

  worksheet.getCell('D4').value = 'Total Records:';
  worksheet.getCell('D4').font = { bold: true, size: 10, color: { argb: 'FF555555' } };
  worksheet.getCell('E4').value = records.length;
  worksheet.getCell('E4').font = { size: 10 };

  // Empty separator row
  worksheet.addRow([]);

  // 4. Table Header Row (Row 6)
  const headerRow = worksheet.addRow([
    'Date (YYYY-MM-DD)',
    'Total no. of Enquiries',
    'Total no. of Responses',
    'Total no. of Confirmations',
    'Total no. of Bookings',
    'Total no. of Bookings (Tomorrow)',
    'No. of WhatsApp Calls/Messages',
    'No. of Normal Calls',
  ]);
  headerRow.height = 30;

  headerRow.eachCell((cell) => {
    cell.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF103B37' }, // Dark forest green
    };
    cell.font = {
      name: 'Arial',
      size: 10,
      bold: true,
      color: { argb: 'FFFFFFFF' },
    };
    cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
    cell.border = {
      top: { style: 'thin', color: { argb: 'FF0D2F2C' } },
      left: { style: 'thin', color: { argb: 'FF0D2F2C' } },
      bottom: { style: 'medium', color: { argb: 'FF0D2F2C' } },
      right: { style: 'thin', color: { argb: 'FF0D2F2C' } },
    };
  });

  // 5. Data Rows
  let sumEnquiries = 0;
  let sumResponses = 0;
  let sumConfirmations = 0;
  let sumBookings = 0;
  let sumTomorrow = 0;
  let sumWhatsApp = 0;
  let sumNormal = 0;

  records.forEach((rec, idx) => {
    const isEven = idx % 2 === 0;
    const row = worksheet.addRow([
      rec.report_date,
      rec.total_enquiries !== null ? rec.total_enquiries : '',
      rec.total_responses !== null ? rec.total_responses : '',
      rec.total_confirmations !== null ? rec.total_confirmations : '',
      rec.total_bookings !== null ? rec.total_bookings : '',
      rec.tomorrow_bookings !== null ? rec.tomorrow_bookings : '',
      rec.whatsapp_calls_messages !== null ? rec.whatsapp_calls_messages : '',
      rec.normal_calls !== null ? rec.normal_calls : '',
    ]);
    row.height = 20;

    if (rec.total_enquiries !== null) sumEnquiries += rec.total_enquiries;
    if (rec.total_responses !== null) sumResponses += rec.total_responses;
    if (rec.total_confirmations !== null) sumConfirmations += rec.total_confirmations;
    if (rec.total_bookings !== null) sumBookings += rec.total_bookings;
    if (rec.tomorrow_bookings !== null) sumTomorrow += rec.tomorrow_bookings;
    if (rec.whatsapp_calls_messages !== null) sumWhatsApp += rec.whatsapp_calls_messages;
    if (rec.normal_calls !== null) sumNormal += rec.normal_calls;

    row.eachCell((cell, colNumber) => {
      cell.font = { name: 'Arial', size: 10 };
      cell.alignment = {
        vertical: 'middle',
        horizontal: colNumber === 1 ? 'center' : 'right',
      };
      cell.border = {
        top: { style: 'thin', color: { argb: 'FFE5E5DC' } },
        bottom: { style: 'thin', color: { argb: 'FFE5E5DC' } },
        left: { style: 'thin', color: { argb: 'FFE5E5DC' } },
        right: { style: 'thin', color: { argb: 'FFE5E5DC' } },
      };
      if (!isEven) {
        cell.fill = {
          type: 'pattern',
          pattern: 'solid',
          fgColor: { argb: 'FFF9FAF8' },
        };
      }
    });
  });

  // 6. Summary / Totals Row
  const totalRow = worksheet.addRow([
    'TOTAL',
    sumEnquiries,
    sumResponses,
    sumConfirmations,
    sumBookings,
    sumTomorrow,
    sumWhatsApp,
    sumNormal,
  ]);
  totalRow.height = 24;

  totalRow.eachCell((cell, colNumber) => {
    cell.font = { name: 'Arial', size: 10, bold: true, color: { argb: 'FF103B37' } };
    cell.alignment = {
      vertical: 'middle',
      horizontal: colNumber === 1 ? 'center' : 'right',
    };
    cell.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FFEAF3F1' }, // subtle teal tint
    };
    cell.border = {
      top: { style: 'thin', color: { argb: 'FF23675B' } },
      bottom: { style: 'double', color: { argb: 'FF103B37' } },
      left: { style: 'thin', color: { argb: 'FFE5E5DC' } },
      right: { style: 'thin', color: { argb: 'FFE5E5DC' } },
    };
  });

  // 7. Column Widths
  worksheet.columns = [
    { width: 18 }, // Date
    { width: 22 }, // Enquiries
    { width: 22 }, // Responses
    { width: 24 }, // Confirmations
    { width: 22 }, // Bookings
    { width: 26 }, // Bookings tomorrow
    { width: 28 }, // WhatsApp
    { width: 20 }, // Normal calls
  ];

  // 8. Generate and download
  const buffer = await workbook.xlsx.writeBuffer();
  const blob = new Blob([buffer], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName || `AyurDesk_Report_${new Date().toISOString().slice(0, 10)}.xlsx`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

